fn minor_arcana() -> Vec<Card> {
    let suits = [Suit::Wands, Suit::Cups, Suit::Swords, Suit::Pentacles];
    let mut cards = Vec::with_capacity(56);
    for suit in suits {
        cards.extend(pips(&suit));
        cards.extend(court(&suit));
    }
    cards
}

fn pips(suit: &Suit) -> Vec<Card> {
    let suit_name = suit.to_string();
    let meanings = [
        (1, "Ace", "creation", "inspiration", "New beginnings in {s}. Creative spark, inspiration, will."),
        (2, "Two", "planning", "decisions", "Planning and decisions in {s}. Choices made, progress begins."),
        (3, "Three", "expansion", "growth", "Expansion and growth in {s}. Momentum, teamwork, initial results."),
        (4, "Four", "stability", "rest", "Stability and rest in {s}. Consolidation, sanctuary, grounding."),
        (5, "Five", "conflict", "loss", "Conflict and loss in {s}. Disruption, competition, setback."),
        (6, "Six", "harmony", "success", "Harmony and success in {s}. Restoration, generosity, victory."),
        (7, "Seven", "perseverance", "strategy", "Perseverance and strategy in {s}. Defense, patience, endurance."),
        (8, "Eight", "movement", "action", "Movement and action in {s}. Swift progress, focus, decisive energy."),
        (9, "Nine", "resilience", "completion", "Resilience and completion in {s}. Gratitude, fullness, sustained effort."),
        (10, "Ten", "culmination", "transition", "Culmination and transition in {s}. End of cycle, legacy, turning point."),
    ];

    meanings
        .iter()
        .map(|(num, label, kw1, kw2, tmpl)| {
            let theme = format!("{label} of {}", human_suit(suit));
            let image = format!("{suit_name}_pip_{num:02}");
            let upright = tmpl.replace("{s}", &human_suit(suit));
            let reversed = format!("Blocked or delayed energy of {theme}.");
            let ctxs = pip_contexts(*num, suit);
            Card {
                id: base_id_for_suit(suit) + num - 1,
                name: theme,
                arcana: Arcana::Minor,
                suit: *suit,
                number: Some(CardNumber(*num)),
                roman_numeral: None,
                upright_meaning: upright,
                reversed_meaning: reversed,
                keywords: vec![kw1.to_string(), kw2.to_string(), suit_name.clone()],
                image_ref: image,
                tone: pip_tone((*num).try_into().unwrap(), suit),
                contexts: ctxs,
            }
        })
        .collect()
}

fn court(suit: &Suit) -> Vec<Card> {
    let suit_name = suit.to_string();
    let courts = [
        ("Page", "Page of {}", "curiosity", "exploration", "Messenger of {s}. New approach, study, enthusiasm."),
        ("Knight", "Knight of {}", "action", "adventure", "Champion of {s}. Momentum, pursuit, daring."),
        ("Queen", "Queen of {}", "nurturing", "mastery", "Keeper of {s}. Mature energy, embodiment, care."),
        ("King", "King of {}", "authority", "leadership", "Ruler of {s}. Command, responsibility, mastery."),
    ];

    courts
        .iter()
        .enumerate()
        .map(|(idx, (_rank, fmt_name, kw1, kw2, tmpl))| {
            let base = base_id_for_suit(suit) + 10;
            let name = fmt_name.replace("{}", &human_suit(suit));
            let upright = tmpl.replace("{s}", &human_suit(suit));
            let reversed = format!("Overdone or withheld expression of {name}.");
            let rank = fmt_name.split_once(" of").map(|s| s.0).unwrap_or("Court");
            let ctxs = court_contexts(rank, suit);
            Card {
                id: base + idx as i32,
                name,
                arcana: Arcana::Minor,
                suit: *suit,
                number: None,
                roman_numeral: None,
                upright_meaning: upright,
                reversed_meaning: reversed,
                keywords: vec![kw1.to_string(), kw2.to_string(), suit_name.clone()],
                image_ref: format!("card_{:02}", base + idx as i32),
                tone: court_tone(suit, *kw1),
                contexts: ctxs,
            }
        })
        .collect()
}

fn base_id_for_suit(suit: &Suit) -> i32 {
    match suit {
        Suit::Wands => 22,
        Suit::Cups => 36,
        Suit::Swords => 50,
        Suit::Pentacles => 64,
        _ => 0,
    }
}

fn human_suit(suit: &Suit) -> String {
    match suit {
        Suit::Wands => "Wands".into(),
        Suit::Cups => "Cups".into(),
        Suit::Swords => "Swords".into(),
        Suit::Pentacles => "Pentacles".into(),
        Suit::None => "None".into(),
    }
}

