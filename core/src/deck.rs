fn pip_tone(num: usize, suit: &Suit) -> Tone {
    match suit {
        Suit::Wands => match num {
            5 | 10 => Tone::Negative,
            1 | 6 | 8 => Tone::Positive,
            _ => Tone::Neutral,
        },
        Suit::Cups => match num {
            5 => Tone::Negative,
            1 | 2 | 3 | 6 | 9 | 10 => Tone::Positive,
            _ => Tone::Neutral,
        },
        Suit::Swords => match num {
            3 | 5 | 7 | 9 | 10 => Tone::Negative,
            _ => Tone::Neutral,
        },
        Suit::Pentacles => match num {
            5 => Tone::Negative,
            1 | 9 | 10 => Tone::Positive,
            _ => Tone::Neutral,
        },
        _ => Tone::Neutral,
    }
}

fn court_tone(suit: &Suit, kw1: &str) -> Tone {
    match (suit, kw1) {
        (Suit::Cups, _) => Tone::Positive,
        (Suit::Wands, "action") | (Suit::Wands, "adventure") => Tone::Positive,
        (Suit::Swords, _) => Tone::Neutral,
        (Suit::Pentacles, "authority") | (Suit::Pentacles, "leadership") => Tone::Neutral,
        _ => Tone::Neutral,
    }
}
